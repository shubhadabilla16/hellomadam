// Defensive truncation and ID sanitization matching firebase-blueprint.json
export function clampStr(val: string | undefined | null, maxLen: number): string {
  if (!val) return '';
  return String(val).trim().slice(0, maxLen);
}

export function sanitizeId(raw: string): string {
  const cleaned = raw.replace(/[^a-zA-Z0-9_-]/g, '-').replace(/-+/g, '-').replace(/^-|-$/g, '');
  return (cleaned || `id-${Date.now()}`).slice(0, 128);
}

export function normalizeEmail(email: string | undefined | null): string {
  return clampStr(email, 160).toLowerCase();
}
